function walk(dir){return readdirSync(dir,{withFileTypes:true}).flatMap(f=>f.isDirectory()?walk(join(dir,f.name)):[join(dir,f.name)])}
for(const file of walk('src')) {
 if(!/\.tsx?$/.test(file)||/\.(test|spec)\./.test(file)||file.includes('/generated/'))continue
 const text=readFileSync(file,'utf8'), source=ts.createSourceFile(file,text,ts.ScriptTarget.Latest,true)
 const changes=[]
 function visit(node){
  if(ts.isPropertySignature(node)&&node.name&&!node.jsDoc?.length){
   const name=node.name.getText(source).replace(/^['"]|['"]$/g,'')
   const note=propDescriptions[name]??(/^on[A-Z]/.test(name)?`Called when ${name.slice(2).replace(/([a-z])([A-Z])/g,'$1 $2').toLowerCase()} occurs. The callback type specifies its arguments.`:undefined)
   if(note){const start=node.getStart(source),line=text.lastIndexOf('\n',start)+1,indent=text.slice(line,start);if(/^\s*$/.test(indent))changes.push({start,text:`/** ${note} */\n${indent}`})}
  }
  ts.forEachChild(node,visit)
 }
 visit(source)
 let next=text
 for(const change of changes.sort((a,b)=>b.start-a.start))next=next.slice(0,change.start)+change.text+next.slice(change.start)
 next=next.replaceAll('uses @container','uses `@container`')
 if(next!==text)writeFileSync(file,next)
}
