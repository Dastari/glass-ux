import ts from "typescript";
import { Application } from "typedoc";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { generateComponentDemos } from "./demos.mjs";
import {
  HTML_ATTRIBUTES_NOTE,
  listsProp,
  literalOptions,
  packageTypePaths,
  propOrigin,
} from "./api-options.mjs";
import {
  documentedEntries,
  entrySpecifiers,
  publicSpecifier,
} from "./entries.mjs";
import { writeSiteModule } from "./site-module.mjs";

/** Generic prop descriptions; a project's `propDescriptions` merge over them. */
const DESCRIPTIONS = {
  children: "The content or component slots rendered inside the component.",
  className:
    "Classes applied to the outer element for layout. Use the component props and theme tokens for its appearance.",
  ref: "Receives the underlying element for focus or measurement. React 19 accepts ref as a normal prop.",
  value:
    "The controlled value. Keep it in application state and update it in the change callback.",
  defaultValue:
    "The initial value when using the component without controlling its state.",
  onValueChange:
    "Called with the next value when a person changes the control. Update controlled state here.",
  onOpenChange:
    "Called when the open state changes, including keyboard dismissal and outside interaction.",
  open: "Controls whether the overlay is open.",
  defaultOpen: "Opens the uncontrolled overlay initially.",
  disabled:
    "Disables interaction while retaining the component’s disabled appearance.",
  readOnly: "Displays the current value without allowing edits.",
  required:
    "Marks the field as required; pair it with the corresponding schema validation.",
  label: "The visible or accessible label for this component.",
  name: "The component’s name or native form field name, as specified by its value type.",
  size: "The token-based size. Touch targets adapt to coarse pointers independently of the selected density.",
  variant:
    "The named visual variant. It is rendered as a data attribute and styled through shared tokens.",
  tone: "The semantic tone. Use danger and warning for consequences and states.",
  render:
    "Base UI composition: supply an element or render function to replace the default element while preserving its behaviour.",
  onClick: "Called when the control is activated by pointer or keyboard.",
  items:
    "The collection rendered by the component. Stable identifiers preserve selection and keyboard focus.",
  options: "The available choices, including their values and visible labels.",
  placeholder:
    "The prompt shown while the value is empty. It does not replace the field’s label.",
  id: "A stable element or component identifier.",
  title: "The heading or title content.",
  description:
    "Additional content describing the value, state, or consequence.",
  icon: "An icon element without an explicit size; the component sizes it through its tokens.",
  onBlur:
    "Called when the element loses focus. Typed inputs normalise on blur rather than while typing.",
};
const slug = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/**
 * Generates the component API pages, their JSON, the focused demos and usage examples, the
 * catalogue, `site.generated.ts`, `llms.txt` and the TypeDoc reference from a project's source.
 */
export async function generateApi(kit) {
  const gallery = kit.galleryDir;
  const specifiers = entrySpecifiers(kit.pkg, kit.outDir);
  const config = ts.readConfigFile("tsconfig.json", ts.sys.readFile);
  mkdirSync(gallery, { recursive: true });
  writeFileSync(
    `${gallery}/release.generated.ts`,
    `// Generated by pnpm docs:api; guide links follow the installed release.\nexport const DOCUMENTATION_VERSION = ${JSON.stringify(kit.version)};\n`,
  );
  const parsed = ts.parseJsonConfigFileContent(
    config.config,
    ts.sys,
    process.cwd(),
  );
  const program = ts.createProgram(parsed.fileNames, parsed.options);
  const checker = program.getTypeChecker();
  const entries = documentedEntries(kit);

  const descriptions = { ...DESCRIPTIONS, ...kit.propDescriptions };
  const doc = (symbol) =>
    ts.displayPartsToString(symbol?.getDocumentationComment(checker) ?? []);
  const seen = new Set();
  const components = [];
  const sources = new Map();
  const pooled = [];
  const familySummary = {};
  const sectionsDir = `${gallery}/sections`;
  mkdirSync(sectionsDir, { recursive: true });
  for (const file of readdirSync(sectionsDir).filter((file) =>
    file.endsWith(".meta.ts"),
  )) {
    const text = readFileSync(join(sectionsDir, file), "utf8");
    const summary = /summary:\s*"([^"]+)"/.exec(text)?.[1];
    if (summary) familySummary[file.replace(".meta.ts", "")] = summary;
  }
  function defaults(declaration) {
    const result = {};
    if (!declaration?.parameters) return result;
    for (const parameter of declaration.parameters) {
      if (ts.isObjectBindingPattern(parameter.name))
        for (const e of parameter.name.elements) {
          if (e.initializer)
            result[(e.propertyName ?? e.name).getText()] =
              e.initializer.getText();
        }
    }
    if (declaration.body?.statements)
      for (const statement of declaration.body.statements)
        if (ts.isVariableStatement(statement))
          for (const binding of statement.declarationList.declarations) {
            if (
              ts.isObjectBindingPattern(binding.name) &&
              binding.initializer &&
              ts.isIdentifier(binding.initializer) &&
              declaration.parameters.some(
                (parameter) =>
                  parameter.name.getText() === binding.initializer.getText(),
              )
            )
              for (const e of binding.name.elements)
                if (e.initializer)
                  result[(e.propertyName ?? e.name).getText()] =
                    e.initializer.getText();
          }
    return result;
  }
  function sourceFunction(at, visited = new Set()) {
    if (!at || visited.has(at)) return null;
    visited.add(at);
    if (at.parameters) return at;
    if (ts.isVariableDeclaration(at) || ts.isPropertyAssignment(at))
      return sourceFunction(at.initializer, visited);
    if (ts.isCallExpression(at)) return sourceFunction(at.arguments[0], visited);
    if (ts.isIdentifier(at) || ts.isShorthandPropertyAssignment(at)) {
      const symbol = ts.isShorthandPropertyAssignment(at)
        ? checker.getShorthandAssignmentValueSymbol(at)
        : checker.getSymbolAtLocation(at);
      return sourceFunction(symbol?.valueDeclaration, visited);
    }
    return null;
  }
  function signatureApi(type, at) {
    const sig = type.getCallSignatures()[0];
    if (!sig) return null;
    const parameter = sig.getParameters()[0];
    const parameterType =
      parameter && checker.getTypeOfSymbolAtLocation(parameter, at);
    const defaultProps = {
      ...defaults(sig.getDeclaration()),
      ...defaults(sourceFunction(at)),
    };
    // Standard React DOM attributes (declared in @types/react) are summarised by a note rather
    // than listed: a Base UI trigger otherwise carries some 290 of them.
    let htmlAttributes = false;
    const props = parameterType
      ? checker
          .getPropertiesOfType(parameterType)
          .filter((prop) => {
            const declaration =
              prop.valueDeclaration ?? prop.declarations?.[0] ?? at;
            const origin = propOrigin(
              declaration.getSourceFile().fileName,
              kit.srcDir,
            );
            if (origin === "react-dom") htmlAttributes = true;
            return listsProp(origin, prop.getName());
          })
          .map((prop) => {
            const declaration =
              prop.valueDeclaration ?? prop.declarations?.[0] ?? at;
            const origin = propOrigin(
              declaration.getSourceFile().fileName,
              kit.srcDir,
            );
            const own = origin === "own";
            const name = prop.getName();
            const propType = checker.getTypeOfSymbolAtLocation(prop, declaration);
            const options = literalOptions(propType);
            const expanded = checker.typeToString(
              propType,
              declaration,
              ts.TypeFormatFlags.NoTruncation,
            );
            // Keep ordinary prop displays stable, but preserve recursive dependency aliases
            // (for example RHF field paths) instead of printing megabytes of conditionals.
            const readableType =
              expanded.length > 1024
                ? checker.typeToString(
                    propType,
                    declaration,
                    ts.TypeFormatFlags.NoTruncation |
                      ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope,
                  )
                : expanded;
            return {
              name,
              type: packageTypePaths(readableType),
              options,
              required: !(prop.flags & ts.SymbolFlags.Optional),
              default: defaultProps[name] ?? null,
              description:
                doc(prop) ||
                descriptions[name] ||
                // Own props must be documented at their declaration; check-docs fails otherwise.
                (own
                  ? ""
                  : origin !== "react-dom"
                    ? "Inherited from the underlying primitive. Its accepted values are specified by the type."
                    : /^on[A-Z]/.test(name)
                      ? "Native React DOM event handler."
                      : "Native React DOM property. Its accepted values are specified by the type."),
              inherited: !own,
            };
          })
          .sort(
            (a, b) =>
              Number(a.inherited) - Number(b.inherited) ||
              a.name.localeCompare(b.name),
          )
      : [];
    return {
      signature: checker.signatureToString(
        sig,
        at,
        ts.TypeFormatFlags.NoTruncation,
      ),
      props,
      // Accepts the element's standard HTML attributes, which are not listed in props.
      htmlAttributes,
    };
  }
  for (const entry of entries) {
    const source = program.getSourceFile(entry.file);
    const module = source && checker.getSymbolAtLocation(source);
    if (!module) continue;
    for (const exported of checker.getExportsOfModule(module)) {
      const name = exported.getName();
      let symbol =
        exported.flags & ts.SymbolFlags.Alias
          ? checker.getAliasedSymbol(exported)
          : exported;
      if (
        !/^[A-Z][a-z]/.test(name) ||
        !(symbol.flags & ts.SymbolFlags.Value) ||
        seen.has(symbol)
      )
        continue;
      const at = symbol.valueDeclaration ?? symbol.declarations?.[0];
      if (!at) continue;
      // Raw primitives, React contexts and error constructors belong in TypeDoc, not the visual catalogue.
      if (
        (ts.isVariableDeclaration(at) &&
          at.initializer?.getText().startsWith("createContext")) ||
        name.endsWith("Context") ||
        name.endsWith("Primitive") ||
        name.endsWith("Error") ||
        at.getSourceFile().fileName.includes("node_modules")
      )
        continue;
      const type = checker.getTypeOfSymbolAtLocation(symbol, at);
      const api = signatureApi(type, at);
      const slots = api
        ? []
        : checker.getPropertiesOfType(type).flatMap((slot) => {
            const slotAt = slot.valueDeclaration ?? at;
            const signature = signatureApi(
              checker.getTypeOfSymbolAtLocation(slot, slotAt),
              slotAt,
            );
            return signature
              ? [{ name: slot.getName(), description: doc(slot), ...signature }]
              : [];
          });
      if (!api && !slots.length) continue;
      seen.add(symbol);
      const family = entry.family ?? slug(name);
      const collection = kit.collections.find(
        (item) => item.family === family || item.alsoFamilies?.includes(family),
      );
      const fallback =
        (collection?.family === family && collection.fallback?.(name)) ||
        (familySummary[family] ??
          `${name} is part of the ${family} component family. Its typed API defines the data, state and application callbacks it accepts.`);
      const component = {
        id: slug(name),
        name,
        entry: entry.entry,
        family,
        description: doc(symbol) || fallback,
        source: at.getSourceFile().fileName.replace(process.cwd() + "/", ""),
        ...api,
        slots,
      };
      (collection ? pooled : components).push(component);
      sources.set(component, entry.file);
    }
  }
  for (const component of components)
    component.section = kit.section?.(component) ?? component.family;
  components.sort((a, b) => a.name.localeCompare(b.name));
  const coverage = await generateComponentDemos(
    kit,
    program,
    checker,
    components,
    sources,
  );
  console.log(
    `Focused demos: ${coverage.filter((c) => c.covered).length}/${coverage.length}; missing: ${coverage
      .filter((c) => !c.covered)
      .map((c) => c.name)
      .join(", ")}`,
  );
  const apiDocs = `${kit.docsDir}/api`;
  mkdirSync(apiDocs, { recursive: true });
  mkdirSync(`${gallery}/api`, { recursive: true });
  const collections = kit.collections.map((collection) => {
    const members = pooled.filter(
      (component) => component.family === collection.family,
    );
    const api = {
      id: collection.id,
      name: collection.name,
      entry: members[0]?.entry,
      description: collection.description,
      props: members[0]?.props ?? [],
      slots: [],
      icons: members.map(({ name, description }) => ({ name, description })),
    };
    writeFileSync(`${gallery}/api/${collection.id}.json`, JSON.stringify(api));
    return { collection, api };
  });
  const currentIds = new Set([
    "README",
    ...kit.collections.map((collection) => collection.id),
    ...components.map((component) => component.id),
  ]);
  for (const file of readdirSync(apiDocs))
    if (file.endsWith(".md") && !currentIds.has(file.replace(".md", "")))
      rmSync(join(apiDocs, file));
  for (const file of readdirSync(`${gallery}/api`))
    if (file.endsWith(".json") && !currentIds.has(file.replace(".json", "")))
      rmSync(join(`${gallery}/api`, file));
  for (const { collection, api } of collections)
    writeFileSync(
      `${apiDocs}/${collection.id}.md`,
      `# ${api.name}\n\n` +
        api.description +
        `\n\n\`import { ${collection.sample} } from "${api.entry}"\`\n\n` +
        (collection.prose ? `${collection.prose}\n\n` : "") +
        api.props
          .filter((prop) => !prop.inherited)
          .map(
            (prop) => `- **${prop.name}**: \`${prop.type}\` — ${prop.description}`,
          )
          .join("\n") +
        `\n\n## Available ${api.name.toLowerCase()}\n\n` +
        api.icons
          .map((icon) => `- **${icon.name}** — ${icon.description}`)
          .join("\n") +
        "\n",
    );

  for (const c of components) {
    const rows = (props) =>
      [
        "| Prop | Type | Valid options | Required | Default | Description |",
        "| --- | --- | --- | --- | --- | --- |",
        ...props.map(
          (p) =>
            `| ${p.name} | \`${p.type.replaceAll("|", "\\|")}\` | ${p.options.map((value) => JSON.stringify(value)).join(", ") || "See type"} | ${p.required ? "yes" : "no"} | ${p.default ?? "—"} | ${p.description.replaceAll("\n", " ")} |`,
        ),
      ].join("\n");
    // The same props as the online API page: own props, then inherited Base UI and documented
    // React props, then a note for the standard HTML attributes neither lists.
    const table = ({ props, htmlAttributes }) => {
      const own = props.filter((p) => !p.inherited);
      const inherited = props.filter((p) => p.inherited);
      return [
        rows(own),
        ...(inherited.length ? ["Inherited properties:", rows(inherited)] : []),
        ...(htmlAttributes ? [HTML_ATTRIBUTES_NOTE] : []),
      ].join("\n\n");
    };
    let content = `# ${c.name}\n\n${c.description}\n\n\`import { ${c.name} } from "${c.entry}"\`\n\n${kit.siteUrl ? `[Live examples](${kit.siteUrl}components/${c.id})\n\n` : ""}`;
    if (c.props) content += "## Props\n\n" + table(c) + "\n\n";
    for (const slot of c.slots)
      content += `## ${c.name}.${slot.name}\n\n${slot.description}\n\n${table(slot)}\n\n`;
    content = content.trimEnd() + "\n";
    writeFileSync(`${apiDocs}/${c.id}.md`, content);
  }
  writeFileSync(`${gallery}/api.generated.json`, JSON.stringify(components));
  for (const component of components)
    writeFileSync(
      `${gallery}/api/${component.id}.json`,
      JSON.stringify(component),
    );
  mkdirSync(`${gallery}/examples`, { recursive: true });
  for (const { id: section } of kit.collections) {
    const file = `${sectionsDir}/${section}.section.tsx`;
    if (!ts.sys.fileExists(file)) continue;
    const text = readFileSync(file, "utf8").replace(
      /(from\s+["'])([^"']+)(["'])/g,
      (_match, before, spec, after) => {
        if (!spec.startsWith(".")) return before + spec + after;
        const resolved = ts.sys
          .resolvePath(join(sectionsDir, spec))
          .replace(`${process.cwd()}/${kit.srcDir}/`, "")
          .replace(/\.js$/, "");
        const entry = publicSpecifier(resolved, specifiers, kit.name);
        if (!entry)
          throw new Error(
            `${file}: imports ${kit.srcDir}/${resolved}, which no package entry exports. Import it from the entry's index module or through a gallery module.`,
          );
        return before + entry + after;
      },
    );
    writeFileSync(`${gallery}/examples/${section}.tsx.txt`, text);
  }
  writeFileSync(
    `${gallery}/catalogue.generated.json`,
    JSON.stringify(
      components.map(({ id, name, entry, family, description, section }) => ({
        id,
        name,
        entry,
        family,
        description: description
          .split(/\n\s*\n/)[0]
          .replaceAll(/\s+/g, " ")
          .split(/(?<=\.)\s+/)[0],
        section,
      })),
    ),
  );
  writeFileSync(
    `${apiDocs}/README.md`,
    "# Component API\n\n" +
      collections
        .map(({ api }) => `- [${api.name}](${api.id}.md) — \`${api.entry}\`\n`)
        .join("") +
      components
        .map((c) => `- [${c.name}](${c.id}.md) — \`${c.entry}\``)
        .join("\n") +
      "\n",
  );
  mkdirSync(`${gallery}/guides`, { recursive: true });
  for (const guide of kit.guides)
    cpSync(`${kit.docsDir}/${guide.id}.md`, `${gallery}/guides/${guide.id}.md`);
  if (kit.llms)
    writeFileSync(
      "llms.txt",
      `# ${kit.title}\n\n${kit.llms.intro}\n\n` +
        kit.llms.links
          .map((link) => `- [${link.title}](${link.path})\n`)
          .join(""),
    );
  writeSiteModule(kit, collections);
  const app = await Application.bootstrapWithPlugins({
    entryPoints: [...entries.map((e) => e.file), ...kit.entries.referenceOnly],
    tsconfig: "tsconfig.json",
    name: kit.title,
    includeVersion: true,
    gitRevision: `v${kit.version}`,
    excludePrivate: true,
    excludeInternal: true,
    excludeExternals: true,
    readme: existsSync("README.md") ? "README.md" : "none",
    out: kit.typedocDir,
    validation: { notExported: false, invalidLink: true, notDocumented: false },
    logLevel: "Warn",
  });
  const project = await app.convert();
  if (!project) throw new Error("TypeDoc could not convert the public API");
  await app.generateDocs(project, kit.typedocDir);
  await app.generateJson(project, `${apiDocs}/typedoc.json`);
  console.log(
    `Generated ${components.length} component API pages, prop tables, compound slots and TypeDoc reference.`,
  );
}
