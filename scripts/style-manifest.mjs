/**
 * Which component stylesheets each public entry needs, and the split of the library
 * stylesheet that lets an application load only those.
 *
 * `glass-ux/styles.css` stays what it was: `@layer …; @import './index.css'`. Beside it the
 * build writes, into dist/styles:
 *
 *   foundation.css   the layer order and every sheet that index.css loads before components.css
 *   adaptations.css  every sheet it loads after (flat, print, forced colours)
 *   manifest.json    the stylesheets each entry needs, in components.css order
 *
 * foundation + the wanted component sheets in components.css order + adaptations is the full
 * library stylesheet with the unused components' rules left out, so the cascade is unchanged.
 * The adaptations are kept whole (about 25 KB, 4 KB gzip): their rules for component classes
 * match nothing when the component is absent, and splitting them per component would move
 * rules of equal specificity relative to each other across flat, print and forced colours.
 *
 * A component's JavaScript never imports its stylesheet, so the closure has four edges:
 *   1. the entry's runtime import graph (type-only imports are elided, as `tsc` does);
 *   2. each module's own sheets: the sheet named after it (select.tsx, select.css) or, when
 *      the folder has none by that name, every sheet in its folder;
 *   3. the sheets defining a `fa-*` class the module names in a string, because components
 *      render classes another component styles without importing it (`fa-radio` is styled by
 *      field.css, `fa-btn` by button.css and button-link.css);
 *   4. between sheets, the sheets declaring a custom property or keyframes that a sheet reads
 *      but does not declare itself (`--_on` from field.css in checkbox.css).
 * Whatever the foundation already defines (a class in recipes.css, a token in tokens.css) needs
 * no component sheet. Selectors that depend on attributes or elements rather than classes are
 * not seen: compare a screen rendered with both stylesheets after changing the closure.
 */
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import postcss from "postcss"
import ts from "typescript"

/** A foundation custom property needs no sheet; a private one declared in more places than this is the element's own. */
const MAX_PROPERTY_DECLARERS = 3

const read = (file) => readFileSync(file, "utf8")

/** The stylesheets `index.css` loads, split around `components.css`. */
export function layerSplit(root) {
  const stylesDir = join(root, "src/styles")
  const imports = [...read(join(stylesDir, "index.css")).matchAll(/@import\s+["']\.\/([^"']+)["']/g)].map((m) => m[1])
  const at = imports.indexOf("components.css")
  if (at === -1) throw new Error("src/styles/index.css must import components.css")
  return { before: imports.slice(0, at), after: imports.slice(at + 1) }
}

/** `foundation.css` and `adaptations.css`: index.css cut around the component stylesheets. */
export function layerSheets(root) {
  const { before, after } = layerSplit(root)
  const layers = /@layer\s+theme[^;]*;/.exec(read(join(root, "src/styles/library.css")))?.[0]
  if (!layers) throw new Error("src/styles/library.css must declare the layer order")
  const lines = (files) => files.map((file) => `@import "./${file}";`).join("\n")
  const head = (what) => `/*\n * Generated by scripts/style-manifest.mjs — do not edit. ${what}\n */\n`
  return {
    "foundation.css": `${head("Everything glass-ux/styles.css loads before the component stylesheets.")}${layers}\n${lines(before)}\n`,
    "adaptations.css": `${head("Everything glass-ux/styles.css loads after the component stylesheets.")}${lines(after)}\n`,
  }
}

/** The component stylesheets in the order components.css imports them, relative to src. */
export function componentStyles(root) {
  const index = read(join(root, "src/styles/components.css"))
  return [...index.matchAll(/@import\s+["']\.\.\/([^"']+)["']/g)].map((m) => m[1])
}

const selectorParts = (selector) => {
  // Top-level combinators only: a compound inside :is() or an attribute value is not one.
  const flat = selector.replace(/\((?:[^()]|\([^()]*\))*\)/g, "()").replace(/\[[^\]]*\]/g, "[]").trim()
  const compounds = flat.split(/\s*[>+~]\s*|\s+/).filter(Boolean)
  const classes = (text) => [...text.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)].map((m) => m[1])
  const subject = compounds.at(-1) ?? ""
  return {
    solo: compounds.length === 1 && classes(subject).length === 1 ? classes(subject)[0] : null,
    subject: classes(subject),
    mentioned: classes(selector),
  }
}

/** What one stylesheet defines and reads: classes, custom properties and keyframes. */
function readSheet(file) {
  const sheet = { solo: new Set(), subject: new Set(), mentioned: new Set(), declares: new Set(), reads: new Set(), keyframes: new Set(), animations: new Set() }
  postcss.parse(read(file)).walk((node) => {
    if (node.type === "atrule") {
      if (node.name.endsWith("keyframes")) sheet.keyframes.add(node.params.trim())
      else if (node.name === "property") sheet.declares.add(node.params.trim())
    } else if (node.type === "rule") {
      if (node.parent?.type === "atrule" && node.parent.name.endsWith("keyframes")) return
      for (const selector of node.selectors) {
        const parts = selectorParts(selector)
        if (parts.solo) sheet.solo.add(parts.solo)
        for (const name of parts.subject) sheet.subject.add(name)
        for (const name of parts.mentioned) sheet.mentioned.add(name)
      }
    } else if (node.type === "decl") {
      if (node.prop.startsWith("--")) sheet.declares.add(node.prop)
      if (/^(-webkit-)?animation(-name)?$/.test(node.prop)) for (const word of node.value.match(/[A-Za-z_][\w-]*/g) ?? []) sheet.animations.add(word)
      // Reads with a fallback tolerate the property being absent.
      for (const m of node.value.matchAll(/var\(\s*(--[\w-]+)\s*([,)])/g)) if (m[2] === ")") sheet.reads.add(m[1])
    }
  })
  return sheet
}

/** Source modules under src, keyed by path relative to src without the extension. */
function sourceModules(src) {
  const modules = new Map()
  const walk = (dir) => {
    for (const name of readdirSync(dir).toSorted()) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) walk(path)
      else if (/\.tsx?$/.test(name) && !/\.(test|d)\.tsx?$/.test(name)) modules.set(relative(src, path).replace(/\.tsx?$/, ""), path)
    }
  }
  walk(src)
  return modules
}

/** The runtime imports and string-literal class tokens of one module, as the emitted JavaScript has them. */
export function analyse(file) {
  const { outputText } = ts.transpileModule(read(file), {
    fileName: file,
    compilerOptions: { target: ts.ScriptTarget.ESNext, module: ts.ModuleKind.ESNext, jsx: ts.JsxEmit.ReactJSX, isolatedModules: true },
  })
  const source = ts.createSourceFile(file, outputText, ts.ScriptTarget.ESNext, true)
  const imports = []
  const tokens = new Set()
  const visit = (node) => {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier && ts.isStringLiteral(node.moduleSpecifier)) imports.push(node.moduleSpecifier.text)
    else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword && ts.isStringLiteralLike(node.arguments[0])) imports.push(node.arguments[0].text)
    else if (ts.isStringLiteralLike(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) {
      const dynamic = ts.isTemplateHead(node) || ts.isTemplateMiddle(node)
      for (const m of node.text.matchAll(/(?<![\w-])fa-[a-z0-9]+(?:-[a-z0-9]+)*-?/g)) {
        // A name cut off by a substitution or a trailing hyphen is a prefix: the rest is built at run time.
        tokens.add(dynamic && m.index + m[0].length === node.text.length && !m[0].endsWith("-") ? `${m[0]}-` : m[0])
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  return { imports, tokens }
}

/**
 * The stylesheets each package entry needs.
 * @returns {{ components: string[], entries: Record<string, string[]>, report: object }}
 */
export function buildStyleManifest(root) {
  const src = join(root, "src")
  const pkg = JSON.parse(read(join(root, "package.json")))
  const components = componentStyles(root)
  const order = new Map(components.map((file, index) => [file, index]))
  const sheets = new Map(components.map((file) => [file, readSheet(join(src, file))]))
  // What the foundation already provides is no reason to load a component's sheet.
  const foundation = layerSplit(root).before.map((file) => readSheet(join(src, "styles", file)))
  const inFoundation = (key, name) => foundation.some((sheet) => sheet[key].has(name))

  // Which sheet(s) define each class. Where no sheet has a rule for the class alone, the sheets
  // whose rule ends in it; failing that, any that mention it.
  const definers = new Map()
  for (const tier of ["solo", "subject", "mentioned"]) {
    for (const [file, sheet] of sheets) {
      for (const name of sheet[tier]) {
        if (inFoundation("solo", name) || inFoundation("subject", name)) continue
        if (definers.has(name) && definers.get(name).tier !== tier) continue
        if (!definers.has(name)) definers.set(name, { tier, files: new Set() })
        definers.get(name).files.add(file)
      }
    }
  }
  const definersOfPrefix = (prefix) => [...definers].filter(([name]) => name.startsWith(prefix)).flatMap(([, { files }]) => [...files])

  // Sheets named by the module that sits beside them.
  const modules = sourceModules(src)
  const ownSheets = new Map()
  for (const file of components) {
    const dir = dirname(file)
    const stem = file.slice(dir.length + 1).replace(/\.css$/, "")
    const beside = [...modules.keys()].filter((key) => dirname(key) === dir)
    const named = beside.filter((key) => key.slice(dir.length + 1) === stem)
    for (const key of named.length ? named : beside) {
      if (!ownSheets.has(key)) ownSheets.set(key, new Set())
      ownSheets.get(key).add(file)
    }
  }

  // Sheets reached through custom properties and keyframes declared in another sheet.
  const declarers = new Map()
  const keyframeDeclarers = new Map()
  const add = (map, key, file) => map.set(key, [...(map.get(key) ?? []), file])
  for (const [file, sheet] of sheets) {
    for (const name of sheet.declares) add(declarers, name, file)
    for (const name of sheet.keyframes) add(keyframeDeclarers, name, file)
  }
  const sheetEdges = new Map()
  for (const [file, sheet] of sheets) {
    const needs = new Set()
    for (const name of sheet.reads) {
      const from = declarers.get(name) ?? []
      if (sheet.declares.has(name) || inFoundation("declares", name) || !from.length || from.length > MAX_PROPERTY_DECLARERS) continue
      for (const other of from) needs.add(other)
    }
    for (const name of sheet.animations) {
      if (sheet.keyframes.has(name) || inFoundation("keyframes", name)) continue
      for (const other of keyframeDeclarers.get(name) ?? []) needs.add(other)
    }
    needs.delete(file)
    sheetEdges.set(file, needs)
  }

  const analysed = new Map()
  const resolve = (from, specifier) => {
    if (!specifier.startsWith(".")) return null
    const target = join(dirname(from), specifier.replace(/\.(m?js|tsx?)$/, ""))
    const key = relative(src, target)
    return [key, `${key}/index`].find((candidate) => modules.has(candidate)) ?? null
  }
  const moduleInfo = (key) => {
    if (!analysed.has(key)) {
      const { imports, tokens } = analyse(modules.get(key))
      analysed.set(key, { imports: imports.map((specifier) => resolve(modules.get(key), specifier)).filter(Boolean), tokens })
    }
    return analysed.get(key)
  }

  const stylesOf = (entry, why = new Map()) => {
    const seen = new Set()
    const wanted = new Set()
    const note = (file, reason) => why.has(file) || why.set(file, reason)
    const stack = [entry]
    while (stack.length) {
      const key = stack.pop()
      if (seen.has(key)) continue
      seen.add(key)
      const { imports, tokens } = moduleInfo(key)
      stack.push(...imports)
      for (const file of ownSheets.get(key) ?? []) {
        wanted.add(file)
        note(file, `own ${key}`)
      }
      for (const token of tokens) {
        const files = token.endsWith("-") ? definersOfPrefix(token) : (definers.get(token)?.files ?? [])
        for (const file of files) {
          wanted.add(file)
          note(file, `token ${token} in ${key}`)
        }
      }
    }
    const queue = [...wanted]
    while (queue.length) {
      const from = queue.pop()
      for (const other of sheetEdges.get(from) ?? []) {
        if (!wanted.has(other)) {
          wanted.add(other)
          note(other, `css edge from ${from}`)
          queue.push(other)
        }
      }
    }
    return [...wanted].toSorted((a, b) => order.get(a) - order.get(b))
  }

  const entries = {}
  for (const [subpath, target] of Object.entries(pkg.exports)) {
    const file = typeof target === "string" ? target : target.import
    if (subpath.includes("*") || !file?.endsWith(".js") || subpath.startsWith("./gallery") || !file.startsWith("./dist/")) continue
    const key = file.replace(/^\.\/dist\//, "").replace(/\.js$/, "")
    if (!modules.has(key)) throw new Error(`export ${subpath} → ${file} has no source module src/${key}.ts(x)`)
    entries[subpath] = stylesOf(key)
  }
  return { components, entries, stylesOf: (key, why) => stylesOf(key.replace(/^\.\//, ""), why) }
}

/** Writes dist/styles/{foundation,adaptations}.css and manifest.json. */
export function writeStyleManifest(root, dist = join(root, "dist")) {
  const { components, entries } = buildStyleManifest(root)
  const out = join(dist, "styles")
  mkdirSync(out, { recursive: true })
  for (const [name, css] of Object.entries(layerSheets(root))) writeFileSync(join(out, name), css)
  const manifest = {
    generated: "Generated by scripts/style-manifest.mjs — do not edit. `glass-ux styles` reads it.",
    foundation: "styles/foundation.css",
    adaptations: "styles/adaptations.css",
    components,
    entries,
  }
  writeFileSync(join(out, "manifest.json"), `${JSON.stringify(manifest, null, 1)}\n`)
  return manifest
}
