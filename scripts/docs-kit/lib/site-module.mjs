import { writeFileSync } from "node:fs";

/** An object's properties as lines of the literal in the generated module. */
const properties = (value) =>
  Object.entries(value)
    .map(([key, item]) => `  ${key}: ${JSON.stringify(item)},`)
    .join("\n");

/** The text of `llms.txt`. A project may give an intro and no links. */
export const llmsText = (kit) =>
  `# ${kit.title}\n\n${kit.llms.intro}\n\n` +
  (kit.llms.links ?? []).map((link) => `- [${link.title}](${link.path})\n`).join("");

/**
 * Writes the module a site passes to `DocsKitProvider`. The `import.meta.glob` calls and the
 * `new URL(..., import.meta.url)` patterns live in these generated files because Vite resolves
 * them against the file containing them, so they have to sit in the project. The globs take `.js`
 * as well as `.ts(x)`: a site reads the sources directly or, like Glass UX's own, the built `dist`.
 *
 * Page content sits in a second module that loads on demand. Vite inlines small assets as data
 * URLs wherever the pattern is, so in `site.generated.ts` every API page and example under its
 * inline limit would join the first chunk, and the demo map would bring its preload lists too.
 *
 * `guides` carries its type because an empty list would otherwise be `never[]`, which stops a
 * project with no guides compiling the site frame.
 *
 * Keep the coverage JSON a dynamic import. Imported statically it changes the order TypeScript
 * creates literal types in, which reorders unions across the generated API pages.
 */
export function writeSiteModule(kit, collections) {
  const gallery = kit.galleryDir;
  const families = { roots: kit.families, related: kit.familyMembers };
  writeFileSync(
    `${gallery}/families.generated.json`,
    `${JSON.stringify(families, null, 2)}\n`,
  );
  const site = {
    title: kit.title,
    packageName: kit.name,
    version: kit.version,
    repositoryUrl: kit.repository ?? null,
    docsSourceUrl: kit.repository
      ? `${kit.repository}/blob/v${kit.version}/${kit.docsDir}/`
      : null,
    collections: collections.map(({ collection, api }) => ({
      id: collection.id,
      name: collection.name,
      entry: api.entry,
      family: collection.family,
      section: collection.id,
      description: collection.summary,
      sample: collection.sample,
    })),
    badges: kit.badges,
  };
  writeFileSync(
    `${gallery}/site.generated.ts`,
    `/// <reference types="vite/client" />
// Generated by pnpm docs:api. Pass \`site\` to DocsKitProvider.
import type { ComponentType } from "react";
import catalogue from "./catalogue.generated.json";
import families from "./families.generated.json";

export const site = {
${properties(site)}
  guides: ${JSON.stringify(kit.guides)} as { id: string; title: string }[],
  catalogue,
  families,
  sectionMetas: import.meta.glob("./sections/*.meta.{js,ts}", { eager: true, import: "meta" }),
  sectionLoaders: import.meta.glob<{ default: ComponentType }>("./sections/*.section.{js,tsx}"),
  loadContent: () => import("./site-content.generated.js"),
  loadGuide: (id: string) =>
    fetch(new URL(\`./guides/\${id}.md\`, import.meta.url).href).then((response) => {
      if (!response.ok) throw new Error("The guide could not load.");
      return response.text();
    }),
};
`,
  );
  writeFileSync(
    `${gallery}/site-content.generated.ts`,
    `/// <reference types="vite/client" />
// Generated by pnpm docs:api. What component pages load on demand; see site.generated.ts.
import type { ComponentType } from "react";

const load = (url: string, failure: string) =>
  fetch(url).then((response) => {
    if (!response.ok) throw new Error(failure);
    return response;
  });

export const loadCoverage = () => import("./demo-coverage.generated.json").then((module) => module.default);

export const demoLoaders = import.meta.glob<{ default: ComponentType }>("./demos/*.{js,tsx}");

export const loadApi = (id: string) =>
  load(new URL(\`./api/\${id}.json\`, import.meta.url).href, "The API reference could not load.").then((response) => response.json());

export const loadExample = (id: string) =>
  load(new URL(\`./examples/\${id}.tsx.txt\`, import.meta.url).href, "Example source could not load.").then((response) => response.text());
`,
  );
}
