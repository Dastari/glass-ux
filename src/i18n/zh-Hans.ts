type CountForms = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }
const counted = (forms: CountForms) => (count: number, locale = "zh-Hans") => {
  const format = (text: string) => text.replaceAll("{n}", numberFormat(locale).format(count))
  return plural("zh-Hans", count, { ...Object.fromEntries(Object.entries(forms).map(([key, text]) => [key, format(text)])), other: format(forms.other) })
}

