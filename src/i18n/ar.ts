type CountForms = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }
const counted = (forms: CountForms) => (count: number, locale = "ar") => {
  const format = (text: string) => text.replaceAll("{n}", numberFormat(locale).format(count))
  return plural("ar", count, { ...Object.fromEntries(Object.entries(forms).map(([key, text]) => [key, format(text)])), other: format(forms.other) })
}

