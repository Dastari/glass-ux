#!/usr/bin/env node
/**
 * Regenerate src/styles/components.css: one @import per component stylesheet, so adding
 * a component never means editing a shared file.
 *
 * Order: foundations components that others refine (icon, surface, skeleton), then the
 * rest of src/ui alphabetically, then src/shell, src/windows, src/features, src/ai and
 * finally the gallery. Everything lives in @layer components, so order only matters where two
 * selectors of equal specificity meet.
 *
 * Also regenerate src/styles/scope-fallback.css: the colour roles declared in @scope blocks,
 * repeated as unscoped rules for browsers without @scope (Firefox before 146, which includes
 * Firefox ESR 140). Each fallback is never more specific than its scoped rule, and an unscoped
 * rule loses a specificity tie to a scoped one, so browsers with @scope cascade as before.
 * Without @scope a page in one mode is exact; a palette island inside a mode island of the
 * other mode takes the outer mode's roles, because only @scope can tell which mode is nearer.
 *
 * Also regenerate every reduced-transparency copy of the Solid rules. Solid
 * (:root[data-glass="solid"]) is written once; the `@media (prefers-reduced-transparency: reduce)`
 * block after a `/* reduced transparency: generated … *\/` comment repeats the Solid rules just
 * before that comment for :root:not([data-glass="full"]), so the OS setting and the Solid
 * preference cannot drift apart, and each copy keeps its place in the cascade.
 *
 * Usage: node scripts/build-styles.mjs [--check]
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"
import postcss from "postcss"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const src = join(root, "src")
const libraryOut = join(src, "styles/components.css")
const galleryOut = join(src, "gallery/styles.css")
const FIRST = ["icon", "surface", "skeleton"]

function cssFiles(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .toSorted()
    .flatMap((name) => {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) return cssFiles(path)
      return name.endsWith(".css") ? [path] : []
    })
}

const ui = cssFiles(join(src, "ui")).toSorted((a, b) => {
  const rank = (p) => {
    const index = FIRST.indexOf(relative(join(src, "ui"), p).split("/")[0])
    return index === -1 ? FIRST.length : index
  }
  return rank(a) - rank(b) || a.localeCompare(b)
})
const library = [...ui, ...cssFiles(join(src, "shell")), ...cssFiles(join(src, "windows")), ...cssFiles(join(src, "ai"))]
const gallery = cssFiles(join(src, "gallery")).filter(file => file !== galleryOut)

// Always "./" or "../": a bare "glassUx/x.css" reads as a package to resolvers other than Vite's
// (prettier-plugin-tailwindcss fails on it).
const importPath = (from, file) => {
  const path = relative(from, file)
  return path.startsWith(".") ? path : `./${path}`
}

const index = (out, files, what) =>
  `/*\n * Generated by scripts/build-styles.mjs — do not edit. ${what}\n */\n` +
  files.map((file) => `@import "${importPath(dirname(out), file)}";`).join("\n") +
  "\n"

const SCOPED = ["styles/themes.css", "styles/brand.css"].map((file) => join(src, file))
const fallbackOut = join(src, "styles/scope-fallback.css")

/** Top-level commas only: `:where(a, b), c` is two selectors. */
const selectorList = (text) => {
  const parts = []
  let depth = 0
  let start = 0
  for (let i = 0; i < text.length; i++) {
    if (text[i] === "(") depth++
    else if (text[i] === ")") depth--
    else if (text[i] === "," && depth === 0) {
      parts.push(text.slice(start, i).trim())
      start = i + 1
    }
  }
  return [...parts, text.slice(start).trim()].filter(Boolean)
}

/**
 * One scoped selector as unscoped selectors with the scope root zeroed by :where():
 * `:scope` matches the root itself, `:scope:is(X)` the root when it is also X, and a bare
 * compound `X` either a descendant of the root or the root itself.
 */
function unscoped(selector, scopeRoot, where) {
  const fail = (why) => {
    throw new Error(`${where}: cannot write a fallback for "${selector}" (${why}). Extend scripts/build-styles.mjs.`)
  }
  const zeroed = `:where(${scopeRoot})`
  if (selector === ":scope") return [zeroed]
  const is = /^:scope:is\((.*)\)$/.exec(selector)
  const subject = is ? is[1] : selector
  if (subject.includes(":scope")) fail(":scope outside the start of the selector")
  if (/[\s>+~]/.test(subject.replace(/\([^)]*\)/g, "()").replace(/\[[^\]]*\]/g, "[]"))) fail("a combinator")
  return is ? [`${subject}${zeroed}`] : [`${zeroed} ${subject}`, `${subject}${zeroed}`]
}

function scopeFallback() {
  const blocks = []
  for (const file of SCOPED) {
    const where = relative(root, file)
    postcss.parse(readFileSync(file, "utf8")).walkAtRules("scope", (scope) => {
      if (/\)\s*to\s*\(/.test(scope.params)) throw new Error(`${where}: @scope limits are not supported`)
      if (scope.parent?.type !== "atrule" || scope.parent.name !== "layer") throw new Error(`${where}: @scope must sit directly in a named @layer`)
      const roots = selectorList(scope.params.trim().replace(/^\(|\)$/g, ""))
      for (const rule of scope.nodes) {
        if (rule.type === "comment") continue
        if (rule.type !== "rule" || rule.nodes.some((node) => node.type !== "decl")) {
          throw new Error(`${where}: only flat style rules are supported inside @scope`)
        }
        // One :where() holds every scoping root, so a block needs no copy per root.
        const selectors = selectorList(rule.selector).flatMap((selector) => unscoped(selector, roots.join(", "), where))
        const declarations = rule.nodes.map((decl) => `    ${decl.prop}: ${decl.value};`)
        blocks.push({ layer: scope.parent.params, css: `  ${[...new Set(selectors)].join(",\n  ")} {\n${declarations.join("\n")}\n  }` })
      }
    })
  }
  const layers = [...new Set(blocks.map((block) => block.layer))]
  return (
    "/*\n * Generated by scripts/build-styles.mjs — do not edit. Unscoped copies of the @scope\n" +
    ` * blocks in ${SCOPED.map((file) => relative(src, file)).join(" and ")}, for browsers without @scope\n` +
    " * (Firefox ESR 140). Browsers with @scope cascade exactly as before; the script says why.\n" +
    " * A browser that can report @scope support skips the copies; one that cannot keeps them.\n */\n" +
    "@supports not at-rule(@scope) {\n" +
    layers
      .map((layer) => `@layer ${layer} {\n${blocks.filter((block) => block.layer === layer).map((block) => block.css).join("\n\n")}\n}\n`)
      .join("\n") +
    "}\n"
  )
}

// Every @scope needs a fallback, so the sources above must be the only stylesheets using it.
const unlisted = [...cssFiles(src)].filter(
  (file) => !SCOPED.includes(file) && file !== fallbackOut && /@scope\b/.test(readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "")),
)
if (unlisted.length) {
  console.error(`${unlisted.map((file) => relative(root, file)).join(", ")} use @scope. Add them to SCOPED in scripts/build-styles.mjs and import their fallback.`)
  process.exit(1)
}

const SOLID = ':root[data-glass="solid"]'
const AUTO = ':root:not([data-glass="full"])'
const GENERATED = /^reduced transparency: generated/

/** A stylesheet with each reduced-transparency block regenerated from the Solid rules before it, or null without any. */
function reducedTransparency(file) {
  const source = readFileSync(file, "utf8")
  if (!source.includes("reduced transparency: generated")) return null
  const css = postcss.parse(source)
  const where = relative(root, file)
  css.walkComments((comment) => {
    if (!GENERATED.test(comment.text)) return
    const media = comment.next()
    if (media?.type !== "atrule" || media.name !== "media" || media.params !== "(prefers-reduced-transparency: reduce)")
      throw new Error(`${where}: a "reduced transparency: generated" comment must precede @media (prefers-reduced-transparency: reduce)`)
    const rules = []
    for (let node = comment.prev(); node && node.type !== "atrule"; node = node.prev()) {
      if (node.type === "comment") continue
      if (node.type !== "rule" || !selectorList(node.selector).every((selector) => selector.startsWith(SOLID))) break
      rules.unshift(node)
    }
    if (!rules.length) throw new Error(`${where}: no Solid rules (${SOLID} …) before the generated reduced-transparency block`)
    const indent = (comment.raws.before ?? "").replace(/^\n+/, "")
    media.removeAll()
    for (const rule of rules) {
      const copy = rule.clone({ selector: rule.selector.replaceAll(SOLID, AUTO).replace(/\n/g, "\n  ") })
      copy.raws.before = `\n${indent}  `
      copy.raws.after = `\n${indent}  `
      copy.walkDecls((decl) => {
        decl.raws.before = `\n${indent}    `
      })
      copy.walkComments((note) => note.remove())
      media.append(copy)
    }
    media.raws.after = `\n${indent}`
  })
  return css.toString()
}

const outputs = [
  [libraryOut, index(libraryOut, library, "Every library component's stylesheet.")],
  [galleryOut, index(galleryOut, gallery, "Shared documentation and specimen stylesheets.")],
  [fallbackOut, scopeFallback()],
  ...cssFiles(src)
    .filter((file) => file !== fallbackOut)
    .map((file) => [file, reducedTransparency(file)])
    .filter(([, content]) => content !== null),
]

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([out, content]) => !existsSync(out) || readFileSync(out, "utf8") !== content)
  if (stale.length) {
    console.error(`${stale.map(([out]) => relative(root, out)).join(", ")} stale. Run pnpm styles.`)
    process.exit(1)
  }
  console.log(`styles: ${library.length} library + ${gallery.length} gallery stylesheets indexed, @scope fallback current`)
} else {
  for (const [out, content] of outputs) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== content) writeFileSync(out, content)
  }
  console.log(`styles: indexed ${library.length} library + ${gallery.length} gallery stylesheets, wrote the @scope fallback`)
}
