import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_FILES = /\.(?:[cm]?[jt]s|[jt]sx)$/;
const SKIPPED_FOLDERS = new Set(["node_modules", "dist", "build", "coverage", ".git", ".next", ".nuxt", ".output", ".svelte-kit", ".turbo", ".vite"]);
// `from "glass-ux/x"`, `import "glass-ux/x"`, `import("glass-ux/x")`, `require("glass-ux/x")`.
const IMPORT = /(?:\bfrom\s*|\bimport\s*\(?\s*|\brequire\s*\(\s*)["']glass-ux(\/[^"'?#]*)?["']/g;
// Subpaths that are not component entries.
const NOT_ENTRIES = /^\/(?:styles(?:\.css|\/.*)?|gallery(?:\/.*)?|package\.json|icons\/svg\/.*)$/;

/** The manifest the build wrote beside the package's stylesheets. */
export function readManifest(
  file = fileURLToPath(new URL("../dist/styles/manifest.json", import.meta.url)),
) {
  if (!existsSync(file)) {
    throw new Error(`${file} is missing. Run pnpm build in the glass-ux package first.`);
  }
  return JSON.parse(readFileSync(file, "utf8"));
}

/** `button`, `glass-ux/button`, `./button` and `/button` name the same entry; `glass-ux` is the root. */
export function entryKey(name) {
  const bare = name.replace(/^glass-ux(?=\/|$)/, "").replace(/^\.?\//, "").replace(/\/+$/, "");
  return bare ? `./${bare}` : ".";
}

function sourceFiles(path) {
  if (!existsSync(path)) throw new Error(`--scan: ${path} does not exist`);
  if (!statSync(path).isDirectory()) return SOURCE_FILES.test(path) ? [path] : [];
  return readdirSync(path, { withFileTypes: true }).flatMap((item) =>
    item.isDirectory() && SKIPPED_FOLDERS.has(item.name) ? [] : sourceFiles(join(path, item.name)),
  );
}

/** The `glass-ux/<entry>` subpaths that the sources under the given folders or files import. */
export function scanImports(paths) {
  const found = new Set();
  for (const path of paths) {
    for (const file of sourceFiles(resolve(path))) {
      for (const [, subpath = ""] of readFileSync(file, "utf8").matchAll(IMPORT)) {
        if (!NOT_ENTRIES.test(subpath)) found.add(subpath);
      }
    }
  }
  return [...found].toSorted();
}

/**
 * The stylesheet for the entries: foundation, the union of their component stylesheets in the
 * library's own order, adaptations.
 * @returns {{ css: string, entries: string[], components: string[], unknown: string[] }}
 */
export function renderStyles(manifest, names, command = "glass-ux styles") {
  const entries = [];
  const unknown = [];
  for (const name of names) {
    const key = entryKey(name);
    if (manifest.entries[key]) entries.push(key);
    else unknown.push(name);
  }
  const wanted = new Set(entries.flatMap((key) => manifest.entries[key]));
  const components = manifest.components.filter((file) => wanted.has(file));
  const specifier = (path) => `glass-ux/${path}`;
  const lines = [
    `@import "${specifier(manifest.foundation)}";`,
    ...components.map((file) => `@import "${specifier(`styles/components/${file}`)}";`),
    `@import "${specifier(manifest.adaptations)}";`,
  ];
  const used = entries.map((key) => (key === "." ? "glass-ux" : `glass-ux/${key.slice(2)}`)).toSorted();
  const css =
    `/*\n * Generated by \`${command}\` — do not edit. Use it where you would import glass-ux/styles.css.\n` +
    ` * Entries: ${used.join(", ") || "none"}.\n` +
    ` * Run the command again after importing another glass-ux entry; \`--check\` fails when this file is stale.\n */\n` +
    `${lines.join("\n")}\n`;
  return { css, entries: used, components, unknown };
}

const USAGE = `glass-ux styles [entries...] [--scan <folder|file>]... [--out <file>] [--check]

Writes a stylesheet with only the component styles the entries need. Entries are names such
as button or glass-ux/data-table; --scan finds the glass-ux/<entry> imports in ts, tsx, js,
jsx and mjs sources. --out defaults to glass-ux.css. --check writes nothing and exits 1 when
the file differs from what the scan and entries would produce.`;

/** Runs `glass-ux styles`; returns the exit code. */
export function runStyles(args, { manifest = readManifest(), log = console.log, error = console.error } = {}) {
  const entries = [];
  const scans = [];
  let out = "glass-ux.css";
  let check = false;
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === "--scan" || arg === "--out") {
      const value = args[++i];
      if (!value || value.startsWith("--")) {
        error(`${arg} needs a value\n\n${USAGE}`);
        return 1;
      }
      if (arg === "--scan") scans.push(value);
      else out = value;
    } else if (arg === "--check") check = true;
    else if (arg === "--help" || arg === "-h") {
      log(USAGE);
      return 0;
    } else if (arg.startsWith("--")) {
      error(`Unknown option ${arg}\n\n${USAGE}`);
      return 1;
    } else entries.push(arg);
  }
  if (!entries.length && !scans.length) {
    error(USAGE);
    return 1;
  }
  const names = [...entries, ...scanImports(scans)];
  const command = `glass-ux styles${[...scans.map((path) => `--scan ${path}`), ...entries, ...(out === "glass-ux.css" ? [] : [`--out ${out}`])].map((part) => ` ${part}`).join("")}`;
  const { css, entries: used, components, unknown } = renderStyles(manifest, names, command);
  for (const name of unknown) error(`glass-ux styles: ${name} is not a glass-ux entry with a manifest; skipped`);
  if (!used.length) {
    error(`glass-ux styles: no glass-ux entries found${scans.length ? ` under ${scans.join(", ")}` : ""}`);
    return 1;
  }
  const target = resolve(out);
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== css) {
      error(`${out} is ${existsSync(target) ? "stale" : "missing"} for ${used.join(", ")}. Run: ${command}`);
      return 1;
    }
    log(`${out} is current: ${components.length} component stylesheets for ${used.length} entries`);
    return 0;
  }
  if (!existsSync(target) || readFileSync(target, "utf8") !== css) writeFileSync(target, css);
  log(`${out}: ${components.length} of ${manifest.components.length} component stylesheets for ${used.length} entries`);
  return 0;
}
